// Lengua, tema 2: sinónimos (significan lo mismo) y antónimos (significan lo contrario), también
// con las palabras de la tabla del cuaderno. Las listas largas (`draw`) sacan unas pocas palabras
// distintas cada vez que se juega. Y en frases: cambiar una palabra por su sinónimo, separar las
// palabras de una frase, y arreglar con un antónimo una frase que no tiene sentido.

// A sentence that makes no sense, the word that is wrong, and the choices to put in its place.
const nonsense = (sentence, wrong, choices) => ({
  prompt: `«${sentence}» No tiene sentido. ¿Qué pones en lugar de «${wrong}»?`,
  choices,
  answer: choices[0],
});

// The antonym of `word` made with in- or des- in front: a button for each, in first, and the
// whole word once it is chosen.
const prefixed = (word, prefix) => ({
  prompt: `Lo contrario de ${word}: ¿…${word}?`,
  say: `Lo contrario de ${word}`,
  choices: ['in', 'des'],
  answer: prefix,
  solved: `${prefix}${word}`,
});

// One word to find, typed or said: a synonym or an antonym of `word`, any of `answers` right.
const synonym = (word, ...answers) => ({ prompt: `Un sinónimo de «${word}»`, say: `Un sinónimo de ${word}`, answers });
const antonym = (word, ...answers) => ({ prompt: `Un antónimo de «${word}»`, say: `Un antónimo de ${word}`, answers });

// Words run together, the sentence they make, and two wrong ways to separate them.
const separate = (sentence, ...wrong) => ({
  prompt: `Separa las palabras: ${sentence.replace(/ /g, '')}`,
  say: false,
  choices: [sentence, ...wrong],
  answer: sentence,
});
